export function formatOrdinal(rank: number, lang: Language): string {
  if (lang === 'fr') return rank === 1 ? '1er' : `${rank}ème`;
  if (lang === 'en') {
    const mod100 = rank % 100;
    if (mod100 >= 11 && mod100 <= 13) return `${rank}th`;
    const mod10 = rank % 10;
    if (mod10 === 1) return `${rank}st`;
    if (mod10 === 2) return `${rank}nd`;
    if (mod10 === 3) return `${rank}rd`;
    return `${rank}th`;
  }
  if (lang === 'es' || lang === 'pt') return `${rank}.º`;
  return `المركز ${rank}`;
}

